int main() {
    GuestCarBlock car{};
    car.accel = 1800;
    car.response = 25;
    static const int16_t kGrip[8] = {196, 168, 128, 168, 96, 64, 0, 0};
    static const int16_t kGear[8] = {-95, 116, 162, 227, 318, 446, 0, 0};
    for (int i = 0; i < 8; ++i) { car.tireGrip[i] = kGrip[i]; car.gearRow[i] = kGear[i]; }
    car.gear = 1;
    car.damp1DC = car.damp1E0 = car.damp1E4 = 0x1000;
    // shortcut: shiftAcc/shiftDec zero reproduces the oracle's target-9000
    // branch (oracle acc >= 259740 all blanks), until the 0x21BA70 physics
    // task port supplies the real accumulator.
    car.shiftAcc = 0; car.shiftDec = 0; car.gripRate = 0;

    int firstBad = -1, mismatches = 0;
    for (int i = 0; i < 600; ++i) {
        const Row& r = kRows[i];
        if (r.vblank != i + 1) { std::printf("row order broken at %d\n", i); return 1; }
        // tireIdx (+0x19C) is ground-contact state from the unported physics
        // task; feed it from the capture (oracle: 8192 through vb 516, 9043
        // from 517 - the car left asphalt; the slot selects tireGrip, which
        // scales the throttle word and its slip clamp).
        car.tireIdx = r.vblank < 517 ? 0x2000 : 9043;
        int out = 0;
        gsCarUpdateMotion(car, gearPolicyA, /*pad gas*/ 1, r.motion, /*latPos*/ 0,
                          /*drivable*/ true, &out);
        if (car.gear != r.gear || car.rpm != r.rpm || car.wheelArc != r.arc) {
            ++mismatches;
            if (firstBad < 0) {
                firstBad = r.vblank;
                std::printf("[mismatch] vblank %d: gear %d/%d rpm %d/%d arc %d/%d\n",
                            r.vblank, car.gear, r.gear, (int)car.rpm, r.rpm,
                            car.wheelArc, r.arc);
            }
        }
    }

    if (firstBad >= 0) {
        std::printf("FAIL: %d/%600 blanks mismatch, first at vblank %d\n",
                    mismatches, firstBad);
        return 1;
    }
    std::printf("guest_vehicle: 600/600 open-loop oracle blanks exact OK\n");
    return 0;
}
