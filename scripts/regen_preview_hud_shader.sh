#!/bin/sh
# Regenerate src/native/preview/preview_hud_shaders.h — embedded SPIR-V for
# the HUD glyph pass — from preview_hud.vert / preview_hud.frag.
# Requires glslc (Vulkan SDK or `brew install shaderc`).  Same embedding
# pattern as preview_shaders.h.
set -eu
cd "$(dirname "$0")/../src/native/preview"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
{
    echo '#pragma once'
    echo '// Generated by scripts/regen_preview_hud_shader.sh from preview_hud.vert/'
    echo '// preview_hud.frag (authored shaders). Do not edit by hand.'
    for pair in "preview_hud.vert kPreviewHudVertSpv" "preview_hud.frag kPreviewHudFragSpv"; do
        set -- $pair
        glslc --target-env=vulkan1.0 -mfmt=c -o "$tmp" "$1"
        echo ""
        echo "// $1"
        sed -e "1s|^|inline constexpr unsigned int $2[] = |" -e '$s|}$|};|' "$tmp"
    done
} > preview_hud_shaders.h
echo "wrote preview_hud_shaders.h ($(wc -l < preview_hud_shaders.h) lines)"
