#!/bin/sh
# Regenerate src/native/preview/preview_shaders.h — embedded SPIR-V for the
# 3D scene, UI quad and textured-terrain passes — from the authored GLSL
# sources. Requires glslc (Vulkan SDK or `brew install shaderc`). Same
# embedding pattern as scripts/regen_preview_hud_shader.sh.
set -eu
cd "$(dirname "$0")/../src/native/preview"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
{
    echo '#pragma once'
    echo '// Generated by scripts/regen_preview_shaders.sh from'
    echo '// preview{,_ui,_textured}.vert/.frag (authored shaders). Do not edit by hand.'
    for pair in "preview.vert kPreviewVertSpv" "preview.frag kPreviewFragSpv" \
                "preview_ui.vert kPreviewUiVertSpv" "preview_ui.frag kPreviewUiFragSpv" \
                "preview_textured.vert kPreviewTexturedVertSpv" \
                "preview_textured.frag kPreviewTexturedFragSpv"; do
        set -- $pair
        glslc --target-env=vulkan1.0 -mfmt=c -o "$tmp" "$1"
        echo ""
        echo "// $1"
        sed -e "1s|^|inline constexpr unsigned int $2[] = |" -e '$s|}$|};|' "$tmp"
    done
} > preview_shaders.h
echo "wrote preview_shaders.h ($(wc -l < preview_shaders.h) lines)"
