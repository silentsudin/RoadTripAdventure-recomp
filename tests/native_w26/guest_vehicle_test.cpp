// guest_vehicle_test.cpp — open-loop per-blank check of the translated
// longitudinal car model (guest_vehicle.cpp) against 600 rows captured from
// the oracle in a straight-line race with the gas held: vblanks 1..600 every
// vblank, fields {vblank, motion input, rpm, gear, wheel arc}
// (build/scratch/w9/oracle_step600.csv, blob window 0x198..0x244).
//
// Open-loop topology: the caller gs_controls_car_update (0x21A310) overwrites
// car+0x1D8 = |param_3[2]| every frame (0021a310.c:70) and AdvanceVehicleMotion
// (0x218EE0) writes its motion output only to its stack param_1[2]
// (00218ee0.c:239) — car+0x1D8 is a mirror, not integrator state. The motion
// the integrator sees is integrated upstream in physics task 0x21BA70
// (0021ba70.c:170,389) plus ResolveGroundContact/ApplyCollisionImpulse
// traction trims. So each blank is fed the oracle's own motion input
// (captured 0x1D8 mirror) plus pad gas-held, and rpm/gear/arc are compared
// per blank; the closed-loop premise (our motion driving later blanks) is
// wrong. Lateral velocity param_3[0] is a physics-stack value unobservable
// from the car block, so lat is fed 0 (validated exact through blank 113;
// capture shows motion never negative, brake byte and steer words zero for
// all 600 blanks).
//
// shiftAcc (+0x23C) accumulates in a different function called from
// 0x21BA70:188; the integrator only subtracts shiftDec and zero-clamps. The
// oracle's shiftAcc - shiftDec stays >= 259740 for all 600 blanks, so the
// port's zero-initialised accumulator (acc >= 0) takes the same target-9000
// branch every blank; raw shiftAcc is not compared.

