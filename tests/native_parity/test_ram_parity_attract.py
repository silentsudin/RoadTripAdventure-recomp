def _parity_errors(ram: bytes) -> list[str]:
    errors = []
    for page in range(RAM_SIZE // PAGE_SIZE):
        start = page * PAGE_SIZE
        restored = bytearray(ram[start:start + PAGE_SIZE])
        pins = PINNED_DIFFS.get(page, ())
        differing = 0
        for address, oracle, native in pins:
            actual = ram[address]
            differing += actual != oracle
            if actual == oracle:
                errors.append(f"removed diff @{address:#010x}: oracle={oracle:#04x}, "
                              f"pinned native={native:#04x}; intentional re-pin required")
            elif actual != native:
                errors.append(f"changed diff @{address:#010x}: oracle={oracle:#04x}, "
                              f"native={actual:#04x}, pinned native={native:#04x}")
            restored[address - start] = oracle
        if differing != len(pins):
            errors.append(f"page {page:#x}: pinned-site diff count {differing} != {len(pins)}")
        expected_hash = ORACLE_PAGE_HASHES.get(page, ZERO_PAGE_HASH)
        if hashlib.sha256(restored).hexdigest() != expected_hash:
            errors.append(f"added/changed UNPINNED diff(s) on page {page:#x} "
                          f"[{start:#010x}, {start + PAGE_SIZE:#010x}); "
                          "oracle-restored page hash differs (exact addresses require fresh oracle)")
    return errors


@pytest.mark.skipif(not RT_APP.exists(), reason=f"{RT_APP} not built")
def test_ram_parity_attract(tmp_path):
    dump = tmp_path / "eeram_1306.bin"
    env = dict(
        os.environ,
        RT_APP_NATIVE_BOOT="1", RT_APP_HEADLESS="1", RT_APP_NOAUDIO="1",
        RT_TIME="virtual", RT_APP_FRAMES="1310", RT_RAM_DUMP=f"{VBLANK}:{dump}",
    )
    log = tmp_path / "native.log"
    with log.open("wb") as output:
        result = subprocess.run([str(RT_APP)], cwd=ROOT, env=env, timeout=1800,
                                stdout=output, stderr=subprocess.STDOUT)
    tail = log.read_text(errors="replace")[-4000:]
    assert result.returncode == 0, f"native boot exited {result.returncode}:\n{tail}"
    assert dump.exists(), f"RT_RAM_DUMP produced no file:\n{tail}"
    ram = dump.read_bytes()
    assert len(ram) == RAM_SIZE, f"RAM dump size {len(ram)} != {RAM_SIZE}"
    errors = _parity_errors(ram)
    assert not errors, "Attract full-RAM diff set changed:\n" + "\n".join(errors)
    print("\nPinned diff census (page: bytes): " + ", ".join(
        f"{page:#x}: {len(pins)}" for page, pins in PINNED_DIFFS.items()))
